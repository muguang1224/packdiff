"""Markdown rendering.

The output format is deliberately boring and diff-friendly:

* a short metadata header,
* a language overview table,
* a directory tree,
* one ``### path`` section per file with a properly sized code fence.

Fence sizing matters more than it sounds: a file that *contains* a triple
backtick (READMEs about Markdown, for instance) will silently break the pack
if you always emit three backticks.  :func:`code_fence` picks a fence one
backtick longer than the longest run inside the file.
"""

from __future__ import annotations

import re
from collections.abc import Sequence
from dataclasses import dataclass, field
from datetime import datetime, timezone

from .tokens import DEFAULT_RATIO, estimate_tokens, format_tokens
from .walk import PackedFile, Skipped, format_size

__all__ = ["TreeNode", "build_tree", "code_fence", "render_document"]

_BACKTICK_RUN = re.compile(r"`+")

TREE_STYLES = {
    "unicode": ("├── ", "└── ", "│   ", "    "),
    "ascii": ("|-- ", "`-- ", "|   ", "    "),
}


@dataclass
class TreeNode:
    """A directory node in the rendered tree."""

    dirs: dict[str, TreeNode] = field(default_factory=dict)
    files: list[str] = field(default_factory=list)


def build_tree(paths: Sequence[str]) -> TreeNode:
    """Build a directory tree from a list of posix relative paths."""
    root = TreeNode()
    for path in paths:
        parts = path.split("/")
        node = root
        for part in parts[:-1]:
            node = node.dirs.setdefault(part, TreeNode())
        node.files.append(parts[-1])
    return root


def code_fence(text: str) -> str:
    """Return a backtick fence that cannot be closed early by *text*."""
    longest = max((len(m.group(0)) for m in _BACKTICK_RUN.finditer(text)), default=0)
    return "`" * max(3, longest + 1)


def render_tree(node: TreeNode, style: str = "unicode", prefix: str = "") -> list[str]:
    """Render *node* as a list of tree lines (``tree(1)`` style)."""
    branch, last, pipe, space = TREE_STYLES.get(style, TREE_STYLES["unicode"])
    lines: list[str] = []
    entries: list[tuple[str, TreeNode | None, bool]] = [
        (name, child, True)
        for name, child in sorted(node.dirs.items(), key=lambda kv: (kv[0].lower(), kv[0]))
    ]
    entries += [(name, None, False) for name in sorted(node.files, key=lambda n: (n.lower(), n))]
    for index, (name, child, is_dir) in enumerate(entries):
        final = index == len(entries) - 1
        lines.append(f"{prefix}{last if final else branch}{name}{'/' if is_dir else ''}")
        if is_dir and child is not None:
            lines.extend(render_tree(child, style, prefix + (space if final else pipe)))
    return lines


def _language_table(files: Sequence[PackedFile], limit: int = 12) -> list[str]:
    stats: dict[str, list[int]] = {}
    for packed in files:
        key = packed.language or "text"
        entry = stats.setdefault(key, [0, 0])
        entry[0] += 1
        entry[1] += packed.lines
    ordered = sorted(stats.items(), key=lambda kv: (-kv[1][1], kv[0]))
    head, tail = ordered[:limit], ordered[limit:]
    if tail:
        head.append(
            (
                f"other ({len(tail)})",
                [sum(v[0] for _, v in tail), sum(v[1] for _, v in tail)],
            )
        )
    lines = ["| Language | Files | Lines |", "| --- | ---: | ---: |"]
    for name, (count, lines_count) in head:
        lines.append(f"| {name} | {count} | {lines_count:,} |")
    return lines


def render_document(
    *,
    sections: Sequence[tuple[str, Sequence[PackedFile]]],
    version: str,
    generated_at: datetime,
    omitted: Sequence[PackedFile] = (),
    skipped: Sequence[Skipped] = (),
    show_tree: bool = True,
    tree_style: str = "unicode",
    max_tokens: int | None = None,
    token_ratio: float = DEFAULT_RATIO,
) -> str:
    """Render the final Markdown pack."""
    if generated_at.tzinfo is None:
        generated_at = generated_at.replace(tzinfo=timezone.utc)
    stamp = generated_at.astimezone(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    multi_root = len(sections) > 1
    all_files = [f for _, files in sections for f in files]

    def display(label: str, packed: PackedFile) -> str:
        return f"{label}/{packed.path}" if multi_root else packed.path

    # ---- header (token count is back-filled after the body is known) --------
    header: list[str] = [
        "# ctxpack · repository context pack",
        "",
        f"> Generated by ctxpack v{version} on {stamp}.",
        f"> Roots: {', '.join('`' + label + '`' for label, _ in sections) or '_(none)_'}",
    ]

    # The body is assembled as a list of blocks joined by exactly one blank
    # line, so the output stays stable no matter which sections are present.
    blocks: list[str] = []

    if not all_files:
        blocks.append(
            "## No files matched\n\nEvery candidate file was ignored, binary or secret-like."
        )
    else:
        blocks.append("## Overview\n\n" + "\n".join(_language_table(all_files)))

        if show_tree:
            tree_lines: list[str] = []
            for label, files in sections:
                tree_lines.append(f"{label}/")
                tree_lines.extend(render_tree(build_tree([f.path for f in files]), tree_style))
            blocks.append("## Directory tree\n\n```text\n" + "\n".join(tree_lines) + "\n```")

        file_blocks: list[str] = []
        for label, files in sections:
            if multi_root and files:
                file_blocks.append(f"### Root `{label}`")
            for packed in files:
                fence = code_fence(packed.text)
                lang = packed.language or ""
                file_blocks.append(
                    f"### `{display(label, packed)}`\n"
                    f"{fence}{lang}\n{packed.text.rstrip(chr(10))}\n{fence}"
                )
        if file_blocks:
            blocks.append("## Files\n\n" + "\n\n".join(file_blocks))

    if omitted:
        lines = ["These files matched but did not fit; raise `--max-tokens` to include them.", ""]
        for packed in sorted(omitted, key=lambda item: item.path):
            size = format_size(packed.size)
            tokens = format_tokens(packed.tokens)
            lines.append(f"- `{packed.path}` ({size}, ~{tokens} tokens)")
        blocks.append("## Deferred by token budget\n\n" + "\n".join(lines))

    secrets = [item for item in skipped if "secret" in item.reason]
    if secrets:
        lines = ["Review these before sharing the pack; use `--include-secrets` to override.", ""]
        lines.extend(f"- `{item.path}`" for item in secrets)
        blocks.append("## Skipped as secret-like\n\n" + "\n".join(lines))

    body_text = "\n\n".join(blocks)
    total_tokens = estimate_tokens("\n".join(header) + body_text, token_ratio)

    summary = [
        f"> {len(all_files)} files · {format_size(sum(f.size for f in all_files))} · "
        f"~{format_tokens(total_tokens)} tokens (estimated)"
    ]
    if max_tokens is not None:
        budget = f"> Token budget: {format_tokens(max_tokens)}"
        if omitted:
            budget += f" — {len(omitted)} file(s) deferred"
        summary.append(budget)

    document = "\n".join(header + summary) + "\n\n" + body_text
    return document.rstrip("\n") + "\n"


def utcnow() -> datetime:  # pragma: no cover - trivial wrapper
    return datetime.now(timezone.utc)
